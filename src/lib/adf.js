// Builds an Atlassian Document Format comment from a release analysis.
const text = (t, marks) => (marks ? { type: 'text', text: t, marks } : { type: 'text', text: t });
const para = (...content) => ({ type: 'paragraph', content });
const bullets = (items) => ({
  type: 'bulletList',
  content: items.map((i) => ({ type: 'listItem', content: [para(text(i))] })),
});

const PANEL = { GO: 'success', CAUTION: 'warning', 'NO-GO': 'error' };

export function reportToAdf(result, { generatedAt = new Date() } = {}) {
  const content = [];
  content.push({
    type: 'panel',
    attrs: { panelType: PANEL[result.verdict] || 'info' },
    content: [para(
      text(`GoNoGo: ${result.verdict}`, [{ type: 'strong' }]),
      text(` for ${result.version?.name || 'this release'}, confidence ${result.score}/100. ${result.totals.done}/${result.totals.issues} issues done.`),
    )],
  });
  if (result.checks.length) {
    content.push(para(text('Risks found', [{ type: 'strong' }])));
    content.push(bullets(result.checks.map((c) => `${c.label} (${c.count}, -${c.penalty}): ${c.issues.slice(0, 5).map((i) => (i.key === '-' ? i.detail : i.key)).join(', ')}`)));
  }
  if (result.nextActions.length) {
    content.push(para(text('Next actions', [{ type: 'strong' }])));
    content.push(bullets(result.nextActions));
  }
  content.push(para(text(`Generated by GoNoGo on ${generatedAt.toISOString().slice(0, 16).replace('T', ' ')} UTC.`, [{ type: 'em' }])));
  return { type: 'doc', version: 1, content };
}
